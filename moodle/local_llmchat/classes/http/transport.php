namespace local_llmchat\http;

/**
 * Sends one HTTP request. Production uses {@see curl_transport}; tests inject a fake.
 *
 * @package    local_llmchat
 * @copyright  2026 Matix-Media
 * @license    https://www.gnu.org/copyleft/gpl.html GNU GPL v3 or later
 */
interface transport {
    /**
     * Send a request.
     *
     * @param string $method GET, POST, PUT
     * @param string $url absolute URL
     * @param array $headers list of "Name: value"
     * @param string|null $body
     * @return response
     */
    public function request(string $method, string $url, array $headers, ?string $body): response;
}
